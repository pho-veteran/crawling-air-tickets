import config from '../config.json' with {type:'json'};
import {queryFrom} from '../src/providers/vna-core.mjs';
import {crawl} from '../src/providers/vna-official.mjs';
import {configureTLS} from '../src/shared/tls.mjs';
configureTLS();
const record=await crawl(queryFrom(config));
console.log(JSON.stringify({event:'official_vna_crawl_complete',status:record.status,requests:record.requests,duration_ms:record.duration_ms,reference_only:true}));
if(process.argv.includes('--dry-run'))process.exit(Object.keys(record.leg_errors).length?1:0);
if(!process.env.VNA_FEED_SECRET)throw new Error('VNA_FEED_SECRET is required');
const url='https://crawling-air-tickets.thanhvinhlqt2016.workers.dev/sources/vna';
const r=await fetch(url,{method:'POST',headers:{'content-type':'application/json','x-vna-feed-secret':process.env.VNA_FEED_SECRET},body:JSON.stringify(record),redirect:'error',signal:AbortSignal.timeout(20000)});
if(!r.ok)throw new Error('Official VNA feed delivery HTTP '+r.status);
console.log(JSON.stringify({event:'official_vna_feed_delivered',http:r.status}));
if(Object.keys(record.leg_errors).length)process.exitCode=1;
